//      Documented, not unified.
//   2. `media-upload-missing` is kebab-case (routes/media.ts:507) while every
//      other kind is snake_case. Documented, not renamed.
//   3. `kind` USUALLY equals the error `code`, but that is not an invariant
//      (`media-upload-missing` rides `invalid_payload`); clients discriminate
//      on `kind` and may double-check `code`.
