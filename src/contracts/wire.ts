// ---- conventions (the 1.13.0 rulebook, applied file-wide) ------------------
//
// · Response shapes: `XxxWire` (entity) — net-new endpoint-specific envelopes:
//   `<Method><PathPascal>Response`. Request bodies, net-new:
//   `<Method><PathPascal>Request`; query-string shapes: `<Method><PathPascal>Query`
//   (HTTP method PascalCase + path segments PascalCase, `:params` dropped).
//   Grandfathered pre-1.13.0 names promote/stay VERBATIM, never renamed —
//   renaming is a major bump.
// · Optional `?` keys are OMITTED when null/empty, never emitted as null,
//   unless the field's own doc comment states an explicit non-omit exception.
// · Cross-field request rules ("text or attachments, one required") are doc
//   comments on the request type, not type gymnastics — the type states
//   key-level optionality truthfully; the comment states the semantic rule
//   and where it is enforced.
// · Promoted declarations carry provenance: the source file:line they were
//   transcribed from and the audit-digest item that asked for them.
// · Idempotency-Key — required header on EVERY mutating endpoint. One parse
//   site for all of them: `db/mutation.ts:80-94 requireIdempotencyKey`
//   (`schema.sql` Transaction contract notes, IDEMPOTENCY). Transcribed 1.13.0
//   from that function — digest refunds/S "Document the Idempotency-Key length
//   contract":
//     · missing, non-string, or empty        → 400 `bad_request`
//     · longer than 206 characters           → 400 `bad_request`; the error
//       message names the live number — read it rather than hard-coding this one
//     · sent more than once on one request   → the values are JOINED: Node
//       delivers duplicate non-set-cookie headers as ONE comma-joined string,
//       so the key becomes `"A, B"` — matching NEITHER attempt. mutation.ts:81's
//       array branch is unreachable for this header. SEND THE HEADER EXACTLY
//       ONCE: a proxy or client that duplicates it with a differing value
//       defeats the replay guarantee (the retry becomes a NEW mutation — on a
//       money endpoint, a second charge). 2.6 adversary finding, fix round 1;
//       server-side rejection of comma-joined keys is a phase-3 hardening
//       candidate.
//     · same key + a different `METHOD path`, or a different canonical-JSON body
//       hash                                 → 422 `idempotency_mismatch`
//     · same key still executing             → 409 `idempotency_inflight`
//     · a completed key replays the ORIGINAL status and body verbatim; errors
//       are never stored, so a retry after a failure re-attempts the work
//   There is NO format, charset, or uniqueness rule: any non-empty string within
//   the bound is accepted. A v4 UUID (36 chars) is what both clients mint and
//   what the contract recommends — it is not a validation.
//   206 is DERIVED, not chosen (`mutation.ts:15-70`): 255, Stripe's own
//   idempotency-key cap, minus 49 — the longest suffix this API appends to your
//   key before sending a DERIVED key to Stripe (`:dog:<uuid>:capture`). Adding a
//   longer suffix TIGHTENS the bound automatically, and moving it is a wire
//   change that takes a bump. The bound is application-level only:
//   `idempotency_keys.key` is unbounded `text` (`schema.sql:1539`), so this
//   boundary check IS the whole contract.

