/**
 * THE shared API↔client wire contract — single source of truth.
 *
 * This module is **dependency-free on purpose**: no imports (not Drizzle, not
 * anything). It is the file both clients' `src/api/contracts.ts` are GENERATED
 * from (verbatim + a banner, via each repo's `npm run sync:contracts`), so it
 * must never drag server code (Drizzle schema, Node APIs) into a browser
 * bundle. Keep it pure types + literal value tuples + pure helpers. The
 * generators strip exactly THIS first doc block and copy the rest verbatim —
 * one leading doc block, zero `import` statements, ever.
 *
 * Layout (fixed section order, 1.13.0 — designs/wire-contract-completion.md §2):
 *   §0      this header + WIRE_CONTRACT_VERSION + the conventions block
 *   §1      THE error contract (ApiErrorCode + envelope + details union) — orchestrator-owned
 *   §2      shared enums + value tuples (everything used by ≥2 domains) — orchestrator-owned
 *   §3–§15  one fenced section per domain, ALPHABETICAL:
 *             auth-media · bookings · credits · dogs-profile · enrollments ·
 *             events · memberships · messaging · notifications ·
 *             payments-invoices · rates-availability · refunds · reports
 *   §16     WireTupleConformance (tuple ↔ union set-equality pins) — orchestrator-owned
 *
 * Domain sections are delimited by `// >>> domain:<name>` / `// <<< domain:<name>`
 * fence comments the merge protocol keys on. Within a domain: (a) domain-local
 * enums + tuples → (b) response wires → (c) request bodies + query shapes →
 * (d) per-endpoint 422 union aliases → (e) pure helpers owned by the domain.
 *
 * Two halves, as ever:
 *   1. **Enum unions + value tuples.** Declared here as literals. Their values
 *      are canonically owned by the DB (`schema.sql` → Drizzle `pgEnum`); the
 *      literals here are a hand-maintained mirror that `contracts/conformance.ts`
 *      pins to the Drizzle enums with a compile-time `Equal<…>` assert — so if
 *      `schema.sql` changes an enum, `tsc` fails until this file is updated.
 *      (We assert rather than rewire `pgEnum(...)` because `schema.ts` is
 *      drizzle-introspection-generated and a `db:introspect` pull would clobber
 *      any hand-wired tuple import.) §16 additionally pins every full-union
 *      value tuple to its union, self-contained, so the guard travels with
 *      every generated copy.
 *   2. **Wire interfaces.** The JSON shapes the API emits. snake_case keys are
 *      intentional — they're the literal JSON keys on the wire. These have no
 *      other canonical home, so THIS file is their single definition; the API's
 *      `lib/*Wire.ts` + the staff routes import them from here.
 */

