/**
 * All codes the API can emit. The 23 thrown codes (promoted verbatim from
 * `lib/errors.ts:43`) + `'internal'`, the serializer's fallback for any
 * non-ApiError throw (`auth/plugin.ts:203-206`) — NOT throwable via ApiError's
 * own sites, but a client switch written against the thrown codes alone
 * misses it (api-conventions.md:151). Clients key behavior off `code`;
 * `message` is UI prose.
 */
export type ApiErrorCode =
  | 'unauthenticated' // missing/malformed Authorization header or bad token
  | 'not_provisioned' // token verifies, but no live mirror row for this uid
  | 'forbidden' // authenticated, but the role gate rejected the route
  | 'not_found' // resource exists or doesn't, but not visible to this principal
  | 'bad_request' // client sent a malformed/unaccepted request body
  | 'invalid_payload' // signature OK, but the payload is semantically unusable
  | 'conflict' // request conflicts with current state (e.g. DELETE referenced)
  | 'idempotency_mismatch' // Idempotency-Key reused on a different endpoint+body
  | 'idempotency_inflight' // duplicate Idempotency-Key request still in progress
  | 'ambiguous_principal' // integrity: uid in BOTH owners and staff
  | 'payment_required' // booking blocked — owner has no live payment_methods row
  | 'vaccine_missing' // booking blocked — required vaccines missing/expired (per dog)
  | 'agreement_unsigned' // booking blocked — required agreements unsigned at current version
  | 'insufficient_credits' // booking blocked — per-dog credit balance would go negative
  | 'insufficient_capacity' // booking blocked — day_capacity for (location,date,mode) exhausted
  | 'cohort_full' // enrollment blocked — cohort.filled + requested > cohort.capacity
  | 'eligibility_missing' // enrollment blocked — dog(s) missing OR-prereq for cohort's class
  | 'evaluation_required' // booking blocked — dog(s) missing passed evaluation for gated category
  | 'already_booked' // day-program booking blocked — dog already has a live booking for (category, day)
  | 'already_enrolled' // enrollment blocked — dog already enrolled in this cohort
  | 'already_requested' // request blocked — dog already has an open request of this category
  | 'event_full' // event RSVP blocked — live rsvp dogs + requested > events.capacity
  | 'payment_failed' // a charge was ATTEMPTED and did not complete — nothing was created or settled
  | 'internal'; // serializer fallback for any non-ApiError throw — never thrown as ApiError

