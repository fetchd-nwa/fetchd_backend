// ============================================================================
// §16 · wire tuple conformance (orchestrator-owned)
// ============================================================================
//
// Tuple ↔ union completeness, compile-time. Bidirectional `Equal` proves SET
// equality (a member missing from a tuple narrows `TUPLE[number]` and fails;
// an extra member widens it and fails). Lives IN wire.ts — with its own local
// helpers, since this file cannot import — so the guard travels with every
// generated client copy. Erasable (`type`-only); proven breakable at 1.13.0
// by mutating one tuple member and watching `tsc` fail.
//
// `SESSION_PROGRAMS` is deliberately absent: it is a SUBSET of ReportProgram
// (satisfies-guarded at its declaration), so an `Equal` pin would fail by
// design. `INVOICE_DEEP_LINK_REASONS` and every full-union tuple above are
// pinned.

type Expect<T extends true> = T;
type Equal<A, B> =
  (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;

