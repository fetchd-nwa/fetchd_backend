/**
 * THE deep-link path grammar. Producers call this at emit time so the persisted
 * `deep_link_path` and the FE route table can never disagree. `report` requires
 * `params.dogId`; a missing one throws HERE — failing loud at emit time rather
 * than persisting a broken path. The inline `never` guard makes adding a kind to
 * `NotificationDeepLinkKind` without a case a compile error (this file is
 * dependency-free, so it can't import the shared `assertNever`).
 */
export function deepLinkToPath(link: NotificationDeepLink): string {
  switch (link.kind) {
    case 'booking':
      return `/bookings/${link.id}`;
    case 'report': {
      const dogId = link.params?.dogId;
      if (dogId === undefined || dogId === '') {
        throw new Error('deepLinkToPath: report link requires params.dogId');
      }
      return `/report-card/${dogId}?reportId=${link.id}`;
    }
    case 'thread':
      return `/chat/${link.id}`;
    case 'invoice': {
      // The SPECIFIC invoice (Allison 2026-07-27, decision 1): the owner app
      // opens it as a pop-up modal, so a paid invoice reads confirmed/paid — never
      // "Outstanding". `link.id` is the invoice id (producers pass it since Phase
      // 2), so it's load-bearing now, not a fixed route. Historical rows persist
      // the old query-less `/account/invoices`; the clients' parser keeps
      // accepting those (backward-compat rule) — only NEW emissions carry the id.
      //
      // Since 1.9.0 a payment notification also carries the FRAMING it promised
      // (`params.reason`), because the sheet it opens had no way to know which
      // push sent the owner there — Allison's 2026-07-31 payment-failed and
      // payment-due copy existed but no production host ever passed a reason, so
      // it rendered only under test. Invalid values throw at emit rather than
      // silently shipping a link the client will drop, matching the `report`
      // arm's fail-loud rule above. Omitted → byte-identical to the pre-1.9.0
      // path, so every historical row and every non-payment producer is untouched.
      const reason = link.params?.reason;
      if (reason === undefined) {
        return `/account/invoices?invoiceId=${link.id}`;
      }
      // Widen the tuple rather than narrowing `reason` — asserting it is a valid
      // member is exactly what this line exists to find out.
      if (!(INVOICE_DEEP_LINK_REASONS as readonly string[]).includes(reason)) {
        throw new Error(
          `deepLinkToPath: invoice link reason must be one of ${INVOICE_DEEP_LINK_REASONS.join(' | ')}, got ${reason}`,
        );
      }
      return `/account/invoices?invoiceId=${link.id}&reason=${reason}`;
    }
    case 'membership': {
      // Routing decided AT SEND TIME (Allison 2026-07-27, decision 4): a LONE
      // membership ending deep-links to that dog's subscriptions page; when the
      // SAME owner has MULTIPLE memberships completing in one worker tick
      // (simultaneous endings), the producer omits `params.dogId` so the tap lands
      // on the `/account/memberships` overview instead. `params.dogId` present ⇒
      // the dog page, carrying `?highlight=<membershipId>` so the app one-shot
      // flashes the SPECIFIC ended subscription card (Allison 2026-07-28, R4);
      // `link.id` is that membership id (producers pass it). Absent ⇒ the overview.
      // Historical rows persist the old query-less `/account/memberships` AND the
      // highlight-less `/dog-subscriptions/:dogId`; the parser keeps accepting both
      // (backward-compat rule).
      const dogId = link.params?.dogId;
      return dogId === undefined || dogId === ''
        ? '/account/memberships'
        : `/dog-subscriptions/${dogId}?highlight=${link.id}`;
    }
    case 'dog-profile':
      return `/dog-profile/${link.id}`;
    case 'dog-manage':
      return `/dog-manage/${link.id}`;
    // `credits` aliases `dog-profile` (decision 4): a credits alert routes to the
    // dog whose credits are expiring. `?highlight=credits` is a SENTINEL, not an
    // id — the credits card is a singular surface on that page, not one row among
    // many — and it makes the card one-shot flash so the alert lands on the thing
    // it's about rather than on the page it lives on (Allison 2026-07-29).
    case 'credits':
      return `/dog-profile/${link.id}?highlight=credits`;
    case 'announcement':
      return `/announcement/${link.id}`;
    // The expiring card, flashed in the wallet list (`link.id` is the
    // payment_method id) — same "point at the row, not the page" rule as invoice
    // and membership (Allison 2026-07-29).
    case 'payment-method':
      return `/payment-methods?highlight=${link.id}`;
    // A waitlist OFFER (`link.id` is the waitlist_entries id). Deliberately not
    // a booking link: when `waitlist-spot-open` fires nothing is booked yet —
    // the owner still has to accept, and payment happens on accept (Allison
    // 2026-07-30). Pointing at a booking that doesn't exist would 404.
    case 'waitlist':
      return `/waitlist/${link.id}`;
    default: {
      const unreachable: never = link.kind;
      throw new Error(`deepLinkToPath: unhandled kind ${String(unreachable)}`);
    }
  }
}

